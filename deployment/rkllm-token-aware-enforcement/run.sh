BACKUP_DIR="$BACKUP_ROOT/rkllm-token-aware-enforcement-$STAMP"
TMP_DIR=$(mktemp -d "$CAPTURE_ROOT/.rkllm-token-aware-enforcement.XXXXXX")
mkdir -p "$BACKUP_DIR"
install -m 0600 "$SERVICE" "$BACKUP_DIR/service.py"
install -m 0600 "$FACTORY" "$BACKUP_DIR/wsgi_factory.py"
install -m 0600 "$TESTS" "$BACKUP_DIR/test_service.py"
SERVICE_MODE=$(stat -c '%a' "$SERVICE")
FACTORY_MODE=$(stat -c '%a' "$FACTORY")
TESTS_MODE=$(stat -c '%a' "$TESTS")
APPLIED=0

rollback() {
    [[ "$APPLIED" -eq 1 ]] || return 0
    install -m "$SERVICE_MODE" "$BACKUP_DIR/service.py" "$SERVICE"
    install -m "$FACTORY_MODE" "$BACKUP_DIR/wsgi_factory.py" "$FACTORY"
    install -m "$TESTS_MODE" "$BACKUP_DIR/test_service.py" "$TESTS"
    rm -f -- "$OVERRIDE"
    rm -rf -- "$TOKENIZER_ROOT"
    systemctl --user daemon-reload
    systemctl --user restart "$SERVICE_NAME"
    wait_for_health || return 1
    assert_loopback_listener
    require_file_sha "$SERVICE" "$SOURCE_SHA"
    require_file_sha "$FACTORY" "$FACTORY_SHA"
    require_file_sha "$TESTS" "$TESTS_SHA"
    APPLIED=0
}

cleanup() {
    status=$?
    trap - EXIT
    if ! rollback; then
        printf 'ERROR: failed to restore the verified RKLLM adapter state\n' >&2
        status=1
    fi
    rm -rf -- "$TMP_DIR"
    exit "$status"
}
