    {
        "AIBRAIN_RKLLM_LIBRARY": "/srv/aibrain/production/runtime/librkllmrt.so",
        "AIBRAIN_RKLLM_MODEL": "/srv/aibrain/production/models/Qwen3.5-4B_w8a8_rk3588_ctx4096.rkllm",
        "AIBRAIN_RKLLM_TOKENIZER": os.environ["AIBRAIN_RKLLM_TOKENIZER"],
    },
    backend_loader=lambda library_path, model_path: FakeBackend(),
)
assert app is not None
assert backend.model_id == "rkllm"
print("PASS calibrated tokenizer runtime import")
PY
}

run_runtime_endpoint_tests() {
    "$PYTHON" - <<'PY'
import json
import urllib.error
import urllib.request

def post(payload):
    request = urllib.request.Request(
        "http://127.0.0.1:8081/v1/chat/completions",
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=300) as response:
            return response.status, json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as error:
        return error.code, json.loads(error.read().decode("utf-8"))

status, body = post(
    {
        "model": "rkllm",
        "max_tokens": 768,
        "messages": [{"role": "user", "content": "Reply exactly READY."}],
    }
)
assert status == 200, body
assert body["choices"][0]["message"]["content"].strip(), body

status, body = post(
    {
        "model": "rkllm",
        "max_tokens": 768,
        "messages": [
            {
                "role": "user",
                "content": ("aGVsbG8vKysvPT09" * 300) + " Reply exactly READY.",
            }
        ],
    }
)
assert status == 400, body
assert "mandatory prompt content exceeds safe input budget" in body["error"]["message"], body
print("PASS runtime 768-token and mandatory-oversize checks")
PY
}

for command in curl sha256sum ss base64 tar git install; do
    command -v "$command" >/dev/null || fail "Required command is missing: $command"
done
