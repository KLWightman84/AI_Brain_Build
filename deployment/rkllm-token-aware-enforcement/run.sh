fail() {
    printf 'ERROR: %s\n' "$*" >&2
    exit 1
}

require_file_sha() {
    local path="$1" expected="$2"
    [[ -f "$path" ]] || fail "Required file is missing: $path"
    local observed
    observed=$(sha256sum "$path" | awk '{print $1}')
    [[ "$observed" == "$expected" ]] || fail "SHA-256 mismatch for $path"
}

wait_for_health() {
    local attempt
    for attempt in $(seq 1 35); do
        if curl -fsS "$HEALTH_URL" >/dev/null; then
            return 0
        fi
        sleep 1
    done
    return 1
}

assert_loopback_listener() {
    ss -ltnH | awk '
        $4 == "127.0.0.1:8081" { loopback = 1 }
        $4 ~ /:8081$/ && $4 != "127.0.0.1:8081" { bad = 1 }
        END { exit (loopback && !bad) ? 0 : 1 }
    '
}

run_adapter_tests() {
    "$PYTHON" -m py_compile "$SERVICE" "$FACTORY" "$TESTS"
    "$PYTHON" - "$TESTS" <<'PY'
import runpy
import sys

tests = runpy.run_path(sys.argv[1])
for name in sorted(key for key in tests if key.startswith("test_")):
    tests[name]()
    print(f"PASS {name}")
PY
}

run_runtime_import_test() {
    PYTHONPATH="$TOKENIZER_SITE:$APP/src" AIBRAIN_RKLLM_TOKENIZER="$TOKENIZER_FILE" \
        "$PYTHON" - <<'PY'
import os
from pathlib import Path

from aibrain_rkllm.service import TokenBudgeter
from aibrain_rkllm.wsgi_factory import build_wsgi_application

budgeter = TokenBudgeter.load(Path(os.environ["AIBRAIN_RKLLM_TOKENIZER"]))
